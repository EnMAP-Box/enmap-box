    if args.algs is None:
        to_remove = [f for f in existing if f not in files]
        new_files = [f for f in files if f not in existing]

        print(f'New files: {len(new_files)}')
        for f in new_files:
            print(f)

        print(f'Files to remove (manually): {len(to_remove)}')
        for f in to_remove:
            print(f)
    return 0


